import json, os, socket, subprocess, sys, tempfile, time
from pathlib import Path
from playwright.sync_api import sync_playwright

os.chdir(Path(__file__).resolve().parents[1])

with tempfile.TemporaryDirectory() as directory:
    env = dict(os.environ, DATA_DIR=directory, APP_PASSWORD='test-password-long-enough', TELEGRAM_API_ID='', TELEGRAM_API_HASH='')
    setup = """from app.store import Store
from datetime import datetime, timezone
import json, os
s=Store(os.path.join(os.environ['DATA_DIR'],'offers.db'))
s.execute('INSERT INTO chats VALUES(?,?)',(1,'Grupo teste'))
date=datetime.now(timezone.utc).isoformat()
s.ingest(1,1,'Nintendo Switch em oferta',date,None)
s.ingest(1,2,'Notebook segredo',date,None,source_json=json.dumps({'entities':[{'_':'MessageEntitySpoiler','offset':9,'length':7}]}))
"""
    subprocess.run([sys.executable,'-c',setup],env=env,check=True)
    with socket.socket() as sock:
        sock.bind(('127.0.0.1',0)); port=sock.getsockname()[1]
    server=subprocess.Popen([sys.executable,'-m','uvicorn','app.main:app','--host','127.0.0.1','--port',str(port)],env=env,stdout=subprocess.DEVNULL,stderr=subprocess.DEVNULL)
    try:
        time.sleep(1)
        with sync_playwright() as p:
            browser=p.chromium.launch(headless=True, executable_path=os.environ.get('PLAYWRIGHT_CHROMIUM_EXECUTABLE') or None)
            page=browser.new_page(viewport={'width':390,'height':844},is_mobile=True,has_touch=True)
            errors=[]; page.on('pageerror',lambda error: errors.append(str(error)))
            page.on('console', lambda msg: errors.append(msg.text) if msg.type == 'error' and 'Content Security Policy' in msg.text else None)
            page.goto(f'http://127.0.0.1:{port}/')
            page.locator('#username').fill('admin'); page.locator('#panel-password').fill('test-password-long-enough'); page.get_by_role('button',name='Entrar').tap()
            page.locator('.offer-card').first.wait_for()
            page.evaluate('window.testSentinel = 123')
            def select(locator, text):
                locator.scroll_into_view_if_needed()
                locator.evaluate('''(el, text) => { const walker = document.createTreeWalker(el, NodeFilter.SHOW_TEXT); let node; while ((node = walker.nextNode())) { const at = node.textContent.indexOf(text); if (at >= 0) { const r=document.createRange(); r.setStart(node,at); r.setEnd(node,at+text.length); const s=window.getSelection(); s.removeAllRanges(); s.addRange(r); return; } } throw Error('Texto não encontrado'); }''',text)
                page.locator('.selection-actions').wait_for(state='visible')
                rect=page.locator('.selection-actions').bounding_box()
                assert rect['x'] >= 0 and rect['x']+rect['width'] <= 390 and rect['y'] >= 0 and rect['y']+rect['height'] <= 844
            select(page.locator('.offer-card').filter(has_text='Nintendo').locator('.offer-preview'),'Nintendo')
            assert page.locator('.selection-actions [data-selection-action=rule]').is_visible()
            page.locator('.selection-actions [data-selection-action=rule]').tap()
            page.get_by_text('Regra criada.',exact=False).wait_for()
            assert page.evaluate('window.testSentinel') == 123
            page.goto(f'http://127.0.0.1:{port}/alerts')
            page.locator('.offer-card').filter(has_text='Nintendo Switch em oferta').first.wait_for()
            page.goto(f'http://127.0.0.1:{port}/')
            card=page.locator('.offer-card').filter(has_text='Nintendo')
            card.locator('.offer-summary').tap()
            assert not page.locator('.offer-modal').evaluate('(el)=>el.open')
            assert not card.locator('.offer-detail').evaluate('(el)=>el.open')
            card.locator('.offer-open').tap()
            assert page.locator('.offer-modal').evaluate('(el)=>el.open')
            page.evaluate('''() => { const a=document.createElement('a'); a.className='message-photo'; a.href='/original-image'; a.target='_blank'; a.innerHTML='<img alt="Foto">'; document.querySelector('.offer-modal .modal-content').prepend(a) }''')
            page.locator('.offer-modal .message-photo img').click()
            assert page.locator('.offer-modal').evaluate('(el)=>el.open')
            assert page.context.pages.__len__() == 1
            page.mouse.click(2,2)
            assert not page.locator('.offer-modal').evaluate('(el)=>el.open')
            assert page.locator('.offer-card').filter(has_text='Nintendo').locator('.offer-open').evaluate('(el)=>document.activeElement===el')
            page.locator('.offer-card').filter(has_text='Nintendo').locator('.offer-open').tap()
            select(page.locator('.offer-modal .message-text'),'Switch')
            assert page.locator('.offer-modal .selection-actions').count() == 1
            auto_delete=page.locator('.selection-actions [data-selection-auto-delete]')
            assert not auto_delete.is_checked()
            auto_delete.tap()
            assert auto_delete.is_checked()
            page.once('dialog', lambda dialog: dialog.accept())
            page.locator('.selection-actions [data-selection-action=ignore]').tap()
            page.get_by_text('Palavra adicionada ao filtro com autoexclusão permanente.').wait_for()
            assert page.locator('.offer-modal #action-status').is_visible()
            page.locator('.offer-modal .modal-close').tap()
            page.reload()
            page.locator('.offer-card').filter(has_text='Nintendo').wait_for(state='detached')
            page.locator('.offer-card').filter(has_text='Notebook').locator('.offer-open').tap()
            text=page.locator('.offer-modal .message-text')
            text.evaluate('''el => {const r=document.createRange();r.selectNodeContents(el);const s=window.getSelection();s.removeAllRanges();s.addRange(r)}''')
            page.wait_for_timeout(300)
            assert not page.locator('.selection-actions').is_visible()
            page.locator('.offer-modal .modal-close').tap()
            notebook=page.locator('.offer-card').filter(has_text='Notebook')
            notebook.locator('[data-delete-offer] button').tap()
            notebook.locator('.offer-action-overlay').wait_for(state='visible')
            notebook.locator('[data-card-undo] button').tap()
            notebook.locator('.offer-action-overlay').wait_for(state='hidden')
            assert notebook.locator('.offer-open').evaluate('(el)=>document.activeElement===el')
            page.locator('.nav-toggle').tap()
            page.get_by_role('link',name='Configurações',exact=True).tap()
            page.locator('.settings-accordion').nth(1).locator(':scope > summary').tap()
            page.locator('#gotify-token').fill('valor-sensível-sintético')
            page.locator('#gotify-token').select_text()
            page.wait_for_timeout(300)
            assert not page.locator('.selection-actions').is_visible()
            select(page.locator('#gotify-title'),'Notificações')
            page.route('**/ignored', lambda route: route.fulfill(status=500, json={'detail':'Falha simulada'}), times=1)
            page.locator('.selection-actions [data-selection-action=ignore]').tap()
            page.get_by_text('Falha simulada').wait_for()
            assert page.locator('.selection-actions').is_visible()
            assert page.locator('.selection-actions [data-selection-action=ignore]').is_enabled()
            page.locator('.selection-actions [data-selection-action=rule]').tap()
            page.get_by_text('Regra criada.',exact=False).wait_for()
            assert page.locator('#gotify-token').input_value() == 'valor-sensível-sintético'
            page.evaluate('''() => { const p=document.createElement('p'); p.id='synthetic-selection'; p.textContent='ps5, ps4'; document.querySelector('main').append(p) }''')
            select(page.locator('#synthetic-selection'),'ps5, ps4')
            assert page.locator('.selection-actions [data-selection-action=rule]').is_disabled()
            assert page.locator('.selection-actions [data-selection-action=ignore]').is_enabled()
            assert page.get_by_text('Para criar alerta, selecione um trecho sem vírgula.').is_visible()
            page.locator('#synthetic-selection').evaluate("el => { el.textContent = 'x'.repeat(101) }")
            select(page.locator('#synthetic-selection'),'x' * 101)
            page.get_by_text('Selecione até 100 caracteres.').wait_for()
            assert page.locator('.selection-actions [data-selection-action=rule]').is_disabled()
            assert page.locator('.selection-actions [data-selection-action=ignore]').is_disabled()
            nojs=browser.new_page(java_script_enabled=False)
            nojs.goto(f'http://127.0.0.1:{port}/')
            nojs.locator('#username').fill('admin'); nojs.locator('#panel-password').fill('test-password-long-enough'); nojs.get_by_role('button',name='Entrar').click()
            nojs_card=nojs.locator('.offer-card').filter(has_text='Notebook')
            nojs_card.locator('.offer-summary').click()
            assert nojs_card.locator('.offer-detail').evaluate('(el)=>el.open')
            assert nojs_card.locator('.offer-open').is_hidden()
            nojs.close()
            desktop=browser.new_page(viewport={'width':1365,'height':900})
            desktop.goto(f'http://127.0.0.1:{port}/')
            desktop.locator('#username').fill('admin'); desktop.locator('#panel-password').fill('test-password-long-enough'); desktop.get_by_role('button',name='Entrar').click()
            summary=desktop.locator('.offer-card').filter(has_text='Notebook').locator('.offer-summary')
            text_rect=summary.locator('.offer-preview').evaluate('''el => { const walker=document.createTreeWalker(el,NodeFilter.SHOW_TEXT); let node; while(node=walker.nextNode()){const i=node.textContent.indexOf('Notebook'); if(i>=0){const r=document.createRange();r.setStart(node,i);r.setEnd(node,i+8);const b=r.getBoundingClientRect();return {x:b.x,y:b.y,width:b.width,height:b.height}}} throw Error('Texto não encontrado') }''')
            summary.click()
            assert not desktop.locator('.offer-modal').evaluate('(el)=>el.open')
            assert not summary.locator('xpath=..').evaluate('(el)=>el.open')
            assert summary.evaluate('(el)=>el.tabIndex') == -1
            assert summary.evaluate('(el)=>getComputedStyle(el).cursor') == 'text'
            desktop.locator('.offer-card').filter(has_text='Notebook').locator('.offer-open').focus()
            desktop.keyboard.press('Enter')
            assert desktop.locator('.offer-modal').evaluate('(el)=>el.open')
            desktop.locator('.offer-modal .modal-close').click()
            assert desktop.locator('.offer-card').filter(has_text='Notebook').locator('.offer-open').evaluate('(el)=>document.activeElement===el')
            desktop.mouse.move(text_rect['x']+1,text_rect['y']+text_rect['height']/2)
            desktop.mouse.down()
            desktop.mouse.move(text_rect['x']+text_rect['width']-1,text_rect['y']+text_rect['height']/2,steps=5)
            desktop.mouse.up()
            desktop.wait_for_timeout(250)
            assert not desktop.locator('.offer-modal').evaluate('(el)=>el.open')
            assert desktop.locator('.selection-actions').is_visible()
            assert desktop.evaluate('window.getSelection().toString()')
            desktop.close()
            assert not errors, errors
            print('Chromium: summary não abre, CTA funciona por toque e teclado, fallback sem JS e seleção desktop e móvel aprovados')
            browser.close()
    finally:
        server.terminate(); server.wait()
